#Requires -Modules Logging

# 1. Write the server and game settings from the AQUANOX_* variables into
#    ini/<AQUANOX_CONFIG>_si.des and ini/<AQUANOX_CONFIG>_gi.des, the files `Aqua.exe -host` reads
#    with -si / -gi. They use the same DES format as the stock ini/mp_si.des and ini/mp_gi.des.
#    The files are written through the merged view, so they land in Overlay/. They are regenerated
#    on every start as long as their first line is the marker comment below; a file without it is
#    left alone.
#
# 2. Write the display mode into the player profile (%APPDATA%\AquaNox\config_1_18.txt). The
#    D3D device fails ("desired resolution not found") unless that mode is the Xvfb screen size,
#    so dsp_width/dsp_height/dsp_depth follow WINE_XVFB_SCREEN. Without a profile the game uses a
#    mode Xvfb doesn't have, so the file is created when it's missing (the game uses its defaults
#    for every other setting). g_cdkey comes from AQUANOX_CDKEY: without a key that passes the
#    game's checksum, -host silently opens the main menu instead of hosting.

$marker = '// Generated by the LANCommander image from the AQUANOX_* settings.'
$name   = if ($Env:AQUANOX_CONFIG) { $Env:AQUANOX_CONFIG } else { 'lancommander' }
$iniDir = Join-Path $Env:SERVER_ROOT 'ini'
$siFile = Join-Path $iniDir "$($name)_si.des"
$giFile = Join-Path $iniDir "$($name)_gi.des"

if (-not (Test-Path -Path (Join-Path $Env:SERVER_ROOT 'Aqua.exe'))) {
    Write-Log -Level Error "Aqua.exe not found in $Env:SERVER_ROOT; skipping server configuration"
    return
}

function Format-Bool([string] $Value) {
    if ("$Value".ToLower() -in @('true', '1', 'yes', 'on')) { '1' } else { '0' }
}

function Format-String([string] $Value, [int] $Max, [string] $Setting) {
    $Value = "$Value".Replace('\', '').Replace('"', '')
    if ($Value.Length -gt $Max) {
        Write-Log -Level Warning "$Setting is longer than $Max characters; the game cuts it off"
        $Value = $Value.Substring(0, $Max)
    }
    "`"$Value`""
}

function Format-Int([string] $Value, [int] $Default, [int] $Min, [int] $Max, [string] $Setting) {
    if ([string]::IsNullOrWhiteSpace($Value)) { return $Default }
    $n = 0
    if (-not [int]::TryParse($Value.Trim(), [ref] $n) -or $n -lt $Min -or $n -gt $Max) {
        throw "$Setting must be a whole number from $Min to $Max (got '$Value')"
    }
    $n
}

function Write-Des([string] $Path, [string] $Section, [System.Collections.Specialized.OrderedDictionary] $Values) {
    $lines = @($marker, "// Change the AQUANOX_* variables, or delete this line to edit the file by hand.", '', "[$Section]", '{')
    foreach ($v in $Values.GetEnumerator()) { $lines += "`t$($v.Key) = $($v.Value)" }
    $lines += '}'

    [System.IO.File]::WriteAllText($Path, ($lines -join "`r`n") + "`r`n")
    chown "$($Env:UID):$($Env:GID)" $Path
}

function Test-Managed([string] $Path) {
    -not (Test-Path -Path $Path) -or ((Get-Content -Path $Path -TotalCount 1) -eq $marker)
}

# Map name -> script path and modes. tdm uses the dm maps.
$maps = [ordered]@{
    'dm_narrow'    = @{ Path = 'map/mp_06_dm/script/dm_narrow';    Ctf = $false }
    'dm_vertical'  = @{ Path = 'map/mp_08/script/dm_vertical';     Ctf = $false }
    'dm_nightfall' = @{ Path = 'map/mp_09/script/dm_nightfall';    Ctf = $false }
    'dm_isolation' = @{ Path = 'map/mp_11/script/dm_isolation';    Ctf = $false }
    'dm_sightless' = @{ Path = 'map/mp_13/script/dm_sightless';    Ctf = $false }
    'ctf_liberty'  = @{ Path = 'map/mp_05_ctf/script/ctf_liberty'; Ctf = $true }
    'ctf_stream'   = @{ Path = 'map/mp_10/script/ctf_stream';      Ctf = $true }
    'ctf_canyon'   = @{ Path = 'map/mp_12/script/ctf_canyon';      Ctf = $true }
}

# A bad setting is logged and leaves the previous files in place; the profile below is still set up.
try {
    $gameType = "$Env:AQUANOX_GAME_TYPE".Trim().ToLower()
    if (-not $gameType) { $gameType = 'dm' }
    if ($gameType -notin @('dm', 'tdm', 'ctf')) {
        throw "AQUANOX_GAME_TYPE must be dm, tdm or ctf (got '$Env:AQUANOX_GAME_TYPE')"
    }
    $isCtf = $gameType -eq 'ctf'

    if ((Test-Managed $siFile) -and (Test-Managed $giFile)) {
        # Map rotation
        $names = @("$Env:AQUANOX_MAPS" -split '[,;\s]+' | Where-Object { $_ })
        if ($names.Count -eq 0) {
            $names = @($maps.Keys | Where-Object { $maps[$_].Ctf -eq $isCtf })
        }
        if ($names.Count -gt 16) { throw "AQUANOX_MAPS has $($names.Count) maps; the game takes at most 16" }

        $paths = @(foreach ($n in $names) {
            $key = $n.ToLower()
            if ($maps.Contains($key)) {
                if ($maps[$key].Ctf -ne $isCtf) {
                    throw "AQUANOX_MAPS: $n is a$(if ($isCtf) { ' deathmatch' } else { ' CTF' }) map and can't be used with AQUANOX_GAME_TYPE=$gameType"
                }
                $maps[$key].Path
            } elseif ($n.Contains('/') -or $n.Contains('\')) {
                $n.Replace('\', '/')   # a custom map script path, used as is
            } else {
                throw "AQUANOX_MAPS: unknown map '$n'. Known maps: $($maps.Keys -join ', ')"
            }
        })

        $startMap = 0
        if ($Env:AQUANOX_START_MAP) {
            $i = [array]::IndexOf(@($names | ForEach-Object { $_.ToLower() }), $Env:AQUANOX_START_MAP.Trim().ToLower())
            if ($i -lt 0) { throw "AQUANOX_START_MAP '$Env:AQUANOX_START_MAP' is not in the map rotation" }
            $startMap = $i
        }

        $port = Format-Int $Env:AQUANOX_PORT 30500 1 65535 'AQUANOX_PORT'

        $si = [ordered]@{
            'Name'       = Format-String $(if ($Env:AQUANOX_SERVER_NAME) { $Env:AQUANOX_SERVER_NAME } else { 'AquaNox Server' }) 31 'AQUANOX_SERVER_NAME'
            'Password'   = Format-String $Env:AQUANOX_PASSWORD 31 'AQUANOX_PASSWORD'
            'Location'   = Format-String $Env:AQUANOX_LOCATION 5 'AQUANOX_LOCATION'
            'AdminName'  = Format-String $Env:AQUANOX_ADMIN_NAME 31 'AQUANOX_ADMIN_NAME'
            'AdminMail'  = Format-String $Env:AQUANOX_ADMIN_MAIL 31 'AQUANOX_ADMIN_MAIL'
            'IP'         = '""'
            'Port'       = $port
            'PingLimit'  = Format-Int $Env:AQUANOX_PING_LIMIT 0 0 250 'AQUANOX_PING_LIMIT'
            'MaxPlayers' = Format-Int $Env:AQUANOX_MAX_PLAYERS 16 1 16 'AQUANOX_MAX_PLAYERS'
            'Advertise'  = Format-Bool $Env:AQUANOX_ADVERTISE
            'Dedicated'  = 1
            'NumOfMaps'  = $paths.Count
        }
        for ($i = 0; $i -lt $paths.Count; $i++) { $si["Map$i"] = "`"$($paths[$i])`"" }
        $si['StartMap'] = $startMap

        $gi = [ordered]@{
            'GameType'     = "`"$gameType`""
            'TimeLimit'    = Format-Int $Env:AQUANOX_TIME_LIMIT 10 0 100000 'AQUANOX_TIME_LIMIT'
            'FragLimit'    = Format-Int $Env:AQUANOX_FRAG_LIMIT 20 0 100000 'AQUANOX_FRAG_LIMIT'
            'CaptureLimit' = Format-Int $Env:AQUANOX_CAPTURE_LIMIT 5 0 100000 'AQUANOX_CAPTURE_LIMIT'
            'WeaponStay'   = Format-Bool $Env:AQUANOX_WEAPON_STAY
        }

        Write-Des $siFile 'Server' $si
        Write-Des $giFile 'Game' $gi

        Write-Log "Wrote ini/$($name)_si.des and ini/$($name)_gi.des: $gameType on $($names -join ', '), port $port"
    } else {
        Write-Log "ini/$($name)_si.des or ini/$($name)_gi.des is not managed by this image; using them as is"
    }
} catch {
    Write-Log -Level Error "$($_.Exception.Message). Keeping the previous ini/$($name)_*.des files."
}

# ---- Player profile ----------------------------------------------------------------------------

$user       = if ($Env:USER) { $Env:USER } else { 'lancommander' }
$profileDir = Join-Path $Env:WINEPREFIX "drive_c/users/$user/AppData/Roaming/AquaNox"
$config     = Join-Path $profileDir 'config_1_18.txt'

New-Item -ItemType Directory -Path $profileDir -Force | Out-Null

# WINE_XVFB_SCREEN is WIDTHxHEIGHTxDEPTH; D3D8 has 16 and 32 bit modes, X has 16 and 24
$width, $height, $depth = 640, 480, 32
if ("$Env:WINE_XVFB_SCREEN" -match '^(\d+)x(\d+)(?:x(\d+))?$') {
    $width  = [int]$Matches[1]
    $height = [int]$Matches[2]
    $depth  = if ($Matches[3] -eq '16') { 16 } else { 32 }
}

# Name -> type, value
$cvars = [ordered]@{
    'dsp_width'  = @('s32', "$width")
    'dsp_height' = @('s32', "$height")
    'dsp_depth'  = @('s32', "$depth")
    'dsp_fsaa'   = @('s32', '0')
}
if ($Env:AQUANOX_CDKEY) { $cvars['g_cdkey'] = @('cstring', "`"$($Env:AQUANOX_CDKEY.Trim().Replace('"', ''))`"") }

# The file is a list of `[CVarN] { Name = "..." Type = "..." Value = ... }` blocks. Existing cvars
# are changed in place, missing ones are appended.
$text = if (Test-Path -Path $config) { [System.IO.File]::ReadAllText($config) } else { "// DES file 'config_1_18.txt'.`r`n// Do not modify.`r`n" }
$next = 0
foreach ($m in [regex]::Matches($text, '\[CVar(\d+)\]')) { $next = [Math]::Max($next, [int]$m.Groups[1].Value + 1) }

foreach ($c in $cvars.GetEnumerator()) {
    $type, $value = $c.Value
    $pattern = '(Name = "' + [regex]::Escape($c.Key) + '"\r?\n\s*Type = "\w+"\r?\n\s*Value = )[^\r\n]*'
    if ($text -match $pattern) {
        $text = [regex]::Replace($text, $pattern, '${1}' + $value.Replace('$', '$$'))
    } else {
        $text = $text.TrimEnd() + "`r`n`r`n[CVar$next]`r`n{`r`n`tName = `"$($c.Key)`"`r`n`tType = `"$type`"`r`n`tValue = $value`r`n}`r`n"
        $next++
    }
}
[System.IO.File]::WriteAllText($config, $text)

# touch.txt is left behind when the game doesn't exit cleanly (always, after `docker stop`); with it
# the next start asks whether to reset the audio/video settings.
Remove-Item -Path (Join-Path $profileDir 'touch.txt') -Force -ErrorAction SilentlyContinue

chown -R "$($Env:UID):$($Env:GID)" (Join-Path $Env:WINEPREFIX "drive_c/users/$user/AppData/Roaming")

Write-Log "AquaNox profile: display ${width}x${height}x$depth"
